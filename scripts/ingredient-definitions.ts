/**
 * Assigns purchaseIndex 0-99: equipment groups in EQUIPMENT_IDS order, and
 * within each group in authored order.
 */
export function buildIngredientList(): Ingredient[] {
  const ordered = EQUIPMENT_IDS.flatMap((equipmentId) =>
    INGREDIENT_DEFINITIONS.filter((definition) => definition.equipmentId === equipmentId),
  );

  if (ordered.length !== INGREDIENT_DEFINITIONS.length) {
    throw new Error('ingredient definitions contain an unknown equipmentId');
  }

  return ordered.map((definition, purchaseIndex) => ({ ...definition, purchaseIndex }));
}

export type IngredientDef = {
  id: string;
  name: string;
  category: string;
  equipmentId: EquipmentId;
  flavor: FlavorVector;
  compoundIds: string[];
  newGameStarter?: boolean;
  softResetStarter?: boolean;
};

/**
 * Builds a full FlavorVector from the axes that actually matter for an
 * ingredient; every unlisted continuous axis is 0 and TE defaults to ambient.
 */
function flavor(axes: Partial<FlavorVector>): FlavorVector {
  return {
    SW: 0,
    SA: 0,
    SO: 0,
    BI: 0,
    UM: 0,
    HE: 0,
    FR: 0,
    EA: 0,
    SM: 0,
    PU: 0,
    NU: 0,
    RI: 0,
    LI: 0,
    HT: 0,
    CR: 0,
    ...axes,
    TE: axes.TE ?? 0,
  };
}

